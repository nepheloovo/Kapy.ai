#!/usr/bin/env node
// Bundles resources/godot-reference/ into src/generated/godotReference.ts so the
// main process can write the reference into Godot workspaces without shipping
// loose files beside the compiled app.
//
//   node scripts/generate-godot-reference.mjs          # regenerate
//   node scripts/generate-godot-reference.mjs --check  # exit 1 when stale

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = join(repoRoot, 'resources', 'godot-reference');
const outputPath = join(repoRoot, 'src', 'generated', 'godotReference.ts');
const workspaceDirectory = 'docs/godot-reference';

function listFiles(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const full = join(directory, entry.name);
      if (entry.isDirectory()) return listFiles(full);
      return /\.(md|gd)$/u.test(entry.name) ? [full] : [];
    })
    .sort();
}

export function renderGodotReferenceModule() {
  const entries = listFiles(sourceRoot).map((file) => {
    const workspacePath = `${workspaceDirectory}/${relative(sourceRoot, file).split(sep).join('/')}`;
    return [workspacePath, readFileSync(file, 'utf8')];
  });
  const body = entries
    .map(([path, content]) => `  ${JSON.stringify(path)}: ${JSON.stringify(content)},`)
    .join('\n');
  return `// Generated by scripts/generate-godot-reference.mjs from resources/godot-reference/.
// Do not edit by hand.

export const GODOT_REFERENCE_DIRECTORY = ${JSON.stringify(workspaceDirectory)};

export const GODOT_REFERENCE_FILES: Readonly<Record<string, string>> = {
${body}
};
`;
}

const rendered = renderGodotReferenceModule();
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outputPath, 'utf8');
  } catch {
    // Missing output is stale output.
  }
  if (current !== rendered) {
    console.error('src/generated/godotReference.ts is stale. Run: npm run godot-reference:generate');
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, rendered);
  console.log(`Wrote ${relative(repoRoot, outputPath)}`);
}
